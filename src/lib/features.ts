import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { getCollection, type CollectionEntry } from "astro:content";

export const GROUP_ORDER = [
  "Keyboard & commands",
  "Editing",
  "Code intelligence",
  "Run & debug",
  "Git & diff",
  "Docs & diagrams",
  "Workspace & files",
  "Customization & extensibility",
];

export type FeatureGroup = {
  title: string;
  items: CollectionEntry<"features">[];
};

/** All features grouped (in GROUP_ORDER) and ordered within each group. */
export async function groupedFeatures(): Promise<FeatureGroup[]> {
  const all = await getCollection("features");
  const groupNames = [
    ...new Set([...GROUP_ORDER, ...all.map((f) => f.data.group)]),
  ];
  return groupNames
    .map((title) => ({
      title,
      items: all
        .filter((f) => f.data.group === title)
        .sort(
          (a, b) =>
            a.data.order - b.data.order ||
            a.data.title.localeCompare(b.data.title),
        ),
    }))
    .filter((g) => g.items.length > 0);
}

/** Anchor id for a group heading on /features, e.g. "Git & diff" → "git-diff". */
export const groupId = (title: string) =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

// Thumbnail for a feature card. Real captures (png/jpg/…) win; an SVG stand-in
// (generated by scripts/gen-placeholder-shots.mjs) is the last resort, so a
// dropped-in real screenshot automatically replaces the placeholder.
const shotExts = ["png", "jpg", "jpeg", "webp", "avif", "gif", "svg"];

/** Card thumbnail for a feature, or null when it has no screenshot yet. */
export function featureShot(id: string): string | null {
  // Prefer the generated thumbnail. These cards render ~260px wide, so
  // pointing them at the full-size captures meant shipping 9.5 MB of PNGs for
  // the grid; the WebP thumbs are the same pictures at 0.24 MB total.
  // scripts/gen-thumbs.mjs builds them and runs as part of `npm run build`.
  const thumb = `screenshots/features/thumbs/${id}.webp`;
  if (existsSync(resolve("public", thumb))) return `/${thumb}`;
  const p = shotExts
    .map((e) => `screenshots/features/${id}.${e}`)
    .find((fp) => existsSync(resolve("public", fp)));
  return p ? `/${p}` : null;
}
